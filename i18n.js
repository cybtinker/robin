let LANG = 'en';
function pickLang() {
  try { const s = localStorage.getItem('yv-lang'); if (s && STR[s]) return s; } catch (e) {}
  for (const l of navigator.languages || [navigator.language || 'en']) {
    const k = String(l).toLowerCase().slice(0, 2);
    if (STR[k]) return k;
  }
  return 'en';
}
function t(key, vars) {
  let s = (STR[LANG] && STR[LANG][key]) ?? STR.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}
// Fill every element marked with data-i18n (text), data-i18n-html (markup) or data-i18n-aria (aria-label).
function applyI18n(root = document) {
  document.documentElement.lang = { zh: 'zh-Hans' }[LANG] || LANG;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
function setLang(l) {
  LANG = STR[l] ? l : 'en';
  try { localStorage.setItem('yv-lang', LANG); } catch (e) {}
  applyI18n();
}
LANG = pickLang();
